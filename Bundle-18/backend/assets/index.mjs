/**
 * Baleshhaa cloud image service (Neon Object Storage).
 * - Existing app_media UUIDs and question.image_id remain the canonical references.
 * - Images live in object storage, not as Postgres bytea.
 * - Only signed-in admins may upload; public GET supports quiz covers and flags.
 * - Avoids third-party dependencies by signing SigV4 requests with node:crypto.
 */
import { createHash,createHmac,randomUUID } from 'node:crypto';
const conn=process.env.DATABASE_URL;
if(!conn)throw Error('Missing injected DATABASE_URL');
const dbEndpoint='https://'+new URL(conn).hostname+'/sql';
const storageEndpoint=process.env.AWS_ENDPOINT_URL_S3;
const accessKey=process.env.AWS_ACCESS_KEY_ID;
const secretKey=process.env.AWS_SECRET_ACCESS_KEY;
const region=process.env.AWS_REGION||'eu-central-1';
const bucket='baleshhaa-public-media';
const uuidRE=/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const origins=(process.env.ALLOWED_ORIGINS||'').split(',').map(s=>s.trim()).filter(Boolean);
const json=(value,status=200)=>new Response(JSON.stringify(value),{status,headers:{'content-type':'application/json; charset=utf-8','cache-control':'no-store'}});
const error=(status,code,message)=>json({error:{code,message}},status);
const sha=b=>createHash('sha256').update(b).digest('hex');
const hm=(key,data)=>createHmac('sha256',key).update(data).digest();
async function sql(query,params=[]){
 const r=await fetch(dbEndpoint,{method:'POST',headers:{'content-type':'application/json','Neon-Connection-String':conn},body:JSON.stringify({query,params}),signal:AbortSignal.timeout(16000)});
 const d=await r.json().catch(()=>null);
 if(!r.ok){console.error('Asset DB error',r.status,d?.code);throw Error('DB_ERROR')}
 return d?.rows||[];
}
async function admin(req){
 const bearer=req.headers.get('authorization')||'';
 if(!/^Bearer [A-Za-z0-9_-]{32,}$/.test(bearer))return null;
 const [u]=await sql("SELECT u.id FROM app_sessions s JOIN app_users u ON u.id=s.user_id WHERE s.token_hash=$1 AND s.expires_at>now() AND u.disabled=false AND u.role='admin' LIMIT 1",[sha(bearer.slice(7))]);
 return u||null;
}
function cors(origin){
 const ok=origin&&(origins.includes(origin)||/^https:\/\/[a-z0-9-]+\.figma\.(site|com)$/.test(origin)||/^http:\/\/localhost(:\d+)?$/.test(origin));
 return ok?{'access-control-allow-origin':origin,'vary':'Origin','access-control-allow-methods':'GET,POST,OPTIONS','access-control-allow-headers':'authorization,content-type'}:{};
}
// AWS Signature Version 4. Object keys are generated by us: sha256 hex, no user-controlled paths.
function signedPut(url,bytes,mime){
 if(!storageEndpoint||!accessKey||!secretKey)throw Error('Missing injected Neon Storage credentials');
 const t=new Date().toISOString().replace(/[:-]|\.\d{3}/g,'');
 const day=t.slice(0,8),hash=sha(bytes),host=url.host,scope=day+'/'+region+'/s3/aws4_request';
 const headers='host:'+host+'\n'+'x-amz-content-sha256:'+hash+'\n'+'x-amz-date:'+t+'\n';
 const signed='host;x-amz-content-sha256;x-amz-date';
 const canonical=['PUT',url.pathname,'',headers,signed,hash].join('\n');
 const msg=['AWS4-HMAC-SHA256',t,scope,sha(canonical)].join('\n');
 const key=hm(hm(hm(hm('AWS4'+secretKey,day),region),'s3'),'aws4_request');
 const signature=createHmac('sha256',key).update(msg).digest('hex');
 return {
  'authorization':'AWS4-HMAC-SHA256 Credential='+accessKey+'/'+scope+', SignedHeaders='+signed+', Signature='+signature,
  'x-amz-content-sha256':hash,'x-amz-date':t,'content-type':mime
 };
}
function objectUrl(key){return new URL('/'+bucket+'/'+key,storageEndpoint)}
async function parseJson(req,max){
 const cl=Number(req.headers.get('content-length'));
 if(cl>max)throw Object.assign(Error('Too large'),{status:413});
 const txt=await req.text();
 if(txt.length>max)throw Object.assign(Error('Too large'),{status:413});
 try{return JSON.parse(txt||'{}')}catch{throw Object.assign(Error('Bad JSON'),{status:400})}
}
function verifyImage(b,mime){
 const h=b.subarray(0,16).toString('hex');
 if(mime==='image/png')return h.startsWith('89504e470d0a1a0a');
 if(mime==='image/jpeg')return h.startsWith('ffd8ff');
 if(mime==='image/webp')return b.subarray(0,4).toString()==='RIFF'&&b.subarray(8,12).toString()==='WEBP';
 return false;
}
async function route(req){
 const url=new URL(req.url),p=url.pathname.replace(/\/+$/,'')||'/',method=req.method;
 if((p==='/'||p==='/api/health')&&method==='GET')return json({ok:true,service:'baleshhaa-image-assets',backend:'neon-object-storage'});
 const id=p.match(/^\/api\/assets\/([0-9a-f-]{36})$/i)?.[1];
 if(id&&uuidRE.test(id)&&method==='GET'){
  const [m]=await sql("SELECT mime_type,storage_bucket,storage_key,encode(image_data,'base64') AS legacy_data FROM app_media WHERE id=$1",[id]);
  if(!m)return error(404,'MEDIA_NOT_FOUND','الصورة غير موجودة');
  if(m.storage_key){
   if(m.storage_bucket!==bucket||!/^[a-z0-9/_-]+\.(png|jpg|webp)$/.test(m.storage_key))return error(404,'MEDIA_INVALID','الصورة غير متاحة');
   return new Response(null,{status:302,headers:{location:objectUrl(m.storage_key).toString(),'cache-control':'public,max-age=3600','x-content-type-options':'nosniff'}});
  }
  if(!m.legacy_data)return error(404,'MEDIA_NOT_FOUND','الصورة غير متاحة');
  return new Response(Buffer.from(m.legacy_data,'base64'),{headers:{'content-type':m.mime_type,'cache-control':'public,max-age=3600','x-content-type-options':'nosniff'}});
 }
 if(p==='/api/admin/assets'&&method==='POST'){
  const u=await admin(req);
  if(!u)return error(403,'ADMIN_REQUIRED','رفع الصور متاح للمشرف فقط');
  const b=await parseJson(req,4400000);
  const match=typeof b.dataUrl==='string'&&b.dataUrl.match(/^data:(image\/(?:png|jpeg|webp));base64,([A-Za-z0-9+/=]+)$/);
  if(!match)return error(422,'INVALID_IMAGE','اختر صورة PNG أو JPG أو WebP');
  const bytes=Buffer.from(match[2],'base64');
  if(!bytes.length||bytes.length>3145728)return error(413,'IMAGE_TOO_LARGE','الصورة يجب أن تكون أقل من 3MB');
  if(!verifyImage(bytes,match[1]))return error(422,'INVALID_IMAGE','محتوى الملف لا يطابق امتداد الصورة');
  const digest=sha(bytes);
  const [existing]=await sql("SELECT id FROM app_media WHERE sha256=$1 AND storage_key IS NOT NULL LIMIT 1",[digest]);
  if(existing)return json({id:existing.id,imageUrl:'/api/assets/'+existing.id,reused:true});
  if(!storageEndpoint||!accessKey||!secretKey)return error(503,'STORAGE_UNAVAILABLE','التخزين غير متاح حاليًا');
  const ext=match[1]==='image/jpeg'?'jpg':match[1].split('/')[1];
  const key='images/'+digest.slice(0,2)+'/'+digest+'.'+ext;
  const target=objectUrl(key);
  const res=await fetch(target,{method:'PUT',headers:signedPut(target,bytes,match[1]),body:bytes,signal:AbortSignal.timeout(25000)});
  if(!res.ok){console.error('Object storage upload status',res.status);return error(502,'STORAGE_UPLOAD_FAILED','تعذّر رفع الصورة إلى التخزين')}
  let row;
  try{
   [row]=await sql('INSERT INTO app_media(owner_user_id,mime_type,byte_count,image_data,storage_bucket,storage_key,sha256) VALUES($1,$2,$3,NULL,$4,$5,$6) RETURNING id',[u.id,match[1],bytes.length,bucket,key,digest]);
  }catch(e){
   [row]=await sql("SELECT id FROM app_media WHERE sha256=$1 AND storage_key IS NOT NULL LIMIT 1",[digest]);
   if(!row)throw e;
  }
  return json({id:row.id,imageUrl:'/api/assets/'+row.id,reused:false},201);
 }
 return error(404,'NOT_FOUND','المسار غير موجود');
}
export default {async fetch(req){
 const origin=req.headers.get('origin'),headers=cors(origin);
 if(req.method==='OPTIONS')return new Response(null,{status:origin&&!headers['access-control-allow-origin']?403:204,headers});
 if(origin&&!headers['access-control-allow-origin'])return error(403,'ORIGIN_FORBIDDEN','المصدر غير مسموح');
 try{
  const r=await route(req);
  for(const [k,v] of Object.entries(headers))r.headers.set(k,v);
  return r;
 }catch(e){
  console.error('Asset service',e?.message||'unknown');
  const r=error(e?.status===413?413:e?.status===400?400:500,'ASSET_ERROR','تعذّر تنفيذ الطلب');
  for(const [k,v]of Object.entries(headers))r.headers.set(k,v);
  return r;
 }
}};
